test('measured findings, labeled mock advice, review gate and export work independently', async ({ page }) => {
  const pageErrors = [];
  page.on('pageerror', error => pageErrors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('status')).toContainText('MOCK REHEARSAL');
  await page.getByRole('button', { name: 'Load timing-error fixture' }).click();
  await page.getByRole('button', { name: 'Run measured checks' }).click();
  await expect(page.locator('#findings')).toContainText('ANIMATION_TIME_ORDER');
  const originalHash = await page.locator('#asset-hash').innerText();
  await expect(page.getByRole('button', { name: 'Generate mock advice' })).toBeDisabled();
  await page.locator('#send-approval').check();
  await page.getByRole('button', { name: 'Generate mock advice' }).click();
  await expect(page.locator('#model-label')).toHaveText('MOCK · no model call');
  await expect(page.getByRole('button', { name: 'Export reviewed report' })).toBeDisabled();
  for (const select of await page.locator('#recommendations select').all()) await select.selectOption('defer');
  await page.locator('#human-reviewed').check();
  const pendingDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export reviewed report' }).click();
  const download = await pendingDownload;
  const report = JSON.parse(await readFile(await download.path(), 'utf8'));
  expect(report.asset_sha256).toBe(originalHash);
  expect(report.provider.mode).toBe('mock');
  expect(report.human_review.repair_approved).toBe(false);
  expect(report.human_review.decisions.every(item => item.decision === 'defer')).toBe(true);
  await page.screenshot({ path: process.env.RIG_QA_SCREENSHOT || 'test-results/rig-qa-workflow.png', fullPage: true });
  await page.getByRole('button', { name: 'Run measured checks' }).click();
  await expect(page.locator('#model-label')).toHaveText('Not requested');
  await expect(page.locator('#send-approval')).not.toBeChecked();
  await expect(page.getByRole('button', { name: 'Export reviewed report' })).toBeDisabled();
  expect(pageErrors).toEqual([]);
});

