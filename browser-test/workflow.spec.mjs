import { buildFixture } from '../fixtures/generate.mjs';

test('artist handoff downloads readable measured evidence and investigation steps without AI or repair approval', async ({ page }) => {
  let calls = 0;
  page.on('request', request => { if (request.url().endsWith('/api/recommend')) calls++; });
  await page.goto('/'); await expect(page.locator('#export-handoff')).toBeDisabled();
  await page.locator('#workflow-test').click();
  await expect(page.locator('#export-handoff')).toBeEnabled();
  const hash = await page.locator('#asset-hash').innerText();
  let release;
  const waiting = new Promise(resolve => { release = resolve; });
  await page.route('**/api/export-handoff', async route => { await waiting; await route.continue(); });
  const pending = page.waitForEvent('download');
  await page.locator('#export-handoff').click();
  await expect(page.locator('#export-handoff')).toBeDisabled();
  await expect(page.locator('#workflow-test')).toBeDisabled();
  release();
  const download = await pending;
  expect(download.suggestedFilename()).toBe(`rig-qa-artist-handoff-${hash.slice(0, 12)}.md`);
  const markdown = await readFile(await download.path(), 'utf8');
  for (const text of [hash, '0 through 23', '22 declared vector samples; 23', 'Errors: 3',
    'Human review: **not recorded**', 'Repair approved: **false**', 'Human handoff and recheck']) expect(markdown).toContain(text);
  await expect(page.locator('#handoff-export-note')).toContainText('No new model request');
  await expect(page.locator('#human-reviewed')).not.toBeChecked();
  await expect(page.locator('#asset-hash')).toHaveText(hash);
  await page.locator('#valid-fixture').click();
  await expect(page.locator('#export-handoff')).toBeDisabled();
  await expect(page.locator('#handoff-export-note')).not.toContainText('exported');
  expect(calls).toBe(0);
});

test('visual faults and reviewed prepared-export comparison explain the difference without repairing or spending', async ({ page }) => {
  let calls = 0; const errors = [];
  page.on('request', req => { if (req.url().endsWith('/api/recommend')) calls++; });
  page.on('pageerror', err => errors.push(err.message));
  await page.goto('/'); await page.locator('#workflow-test').click();
  await expect(page.locator('#workflow-visual')).toBeVisible();
  await expect(page.locator('#fault-visual svg')).toHaveCount(2);
  await expect(page.getByRole('img', { name: /highlighted vertex 0/ })).toBeVisible();
  await expect(page.getByRole('img', { name: 'Translation track: 23 timestamps and 22 declared samples' })).toBeVisible();
  await expect(page.locator('#fault-visual')).toContainText('not physically deleted');
  await expect(page.locator('#prepared-recheck')).toBeDisabled();
  const originalHash = await page.locator('#asset-hash').innerText();
  await page.locator('#prepared-reviewed').check(); await page.locator('#prepared-recheck').click();
  await expect(page.locator('#comparison-status')).toContainText('Companion issues: 2 → 0. Official errors: 3 → 0.');
  await expect(page.locator('#corrected-visual')).toContainText('reference: slot 0');
  await expect(page.locator('#corrected-visual')).toContainText('23 declared vector samples / 23 required');
  await expect(page.locator('#asset-hash')).toHaveText(originalHash);
  await expect(page.locator('#findings')).toContainText('JOINT_INDEX_RANGE');
  await expect(page.locator('#official-status')).toContainText('3 error(s)');
  await expect(page.locator('#recommendations select').first()).toHaveValue('');
  await expect(page.locator('#human-reviewed')).not.toBeChecked();
  const pending = page.waitForEvent('download'); await page.locator('#export-comparison').click();
  const comparison = JSON.parse(await readFile(await (await pending).path(), 'utf8'));
  expect(comparison.original_asset_sha256).toBe(originalHash); expect(comparison.original_changed).toBe(false);
  expect(comparison.automatic_repair).toBe(false); expect(comparison.report.findings).toEqual([]);
  expect(comparison.original_inspection.findings).toHaveLength(2);
  expect(createHash('sha256').update(JSON.stringify(comparison.report)).digest('hex')).toBe(comparison.report_sha256);
  await page.locator('#valid-fixture').click();
  await expect(page.locator('#workflow-visual')).toBeHidden();
  await expect(page.locator('#corrected-result')).toBeHidden();
  await expect(page.locator('#prepared-reviewed')).not.toBeChecked();
  // Generic untrusted uploads never acquire the owned fixture's diagrams.
  await page.locator('#asset').setInputFiles({ name: 'generic.glb', mimeType: 'model/gltf-binary', buffer: buildFixture() });
  await page.locator('#rights').check(); await page.locator('#inspect').click();
  await expect(page.locator('#workflow-visual')).toBeHidden();
  expect(calls).toBe(0); expect(errors).toEqual([]);
});

