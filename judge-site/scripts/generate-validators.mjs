// Build-time only: never invoke Ajv code generation inside a Cloudflare Worker.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

// A standalone site uses its own pinned Ajv. Root-only installations can still
// run companion tests before installing the optional site's larger tree.
function loadAjv(base) {
  const require = createRequire(base);
  const Ajv = require('ajv');
  const standaloneCode = require('ajv/dist/standalone/index.js').default;
  const unicodeRuntime = require('ajv/dist/runtime/ucs2length.js');
  if (require('ajv/package.json').version !== '8.20.0') throw new Error('Standalone validators require pinned Ajv 8.20.0.');
  return { Ajv, standaloneCode, unicodeRuntime };
}
let runtime;
try { runtime = loadAjv(new URL('../package.json', import.meta.url)); }
catch (error) {
  if (error.code !== 'MODULE_NOT_FOUND') throw error;
  runtime = loadAjv(new URL('../../package.json', import.meta.url));
}
const { Ajv, standaloneCode, unicodeRuntime } = runtime;

const inspectionSchema = JSON.parse(readFileSync(new URL('../shared/schemas/inspection.schema.json', import.meta.url), 'utf8'));
const adviceSchema = JSON.parse(readFileSync(new URL('../shared/schemas/advice.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv({ strict: true, allErrors: false, code: { source: true, esm: true } });
ajv.addSchema(inspectionSchema, 'inspection');
ajv.addSchema(adviceSchema, 'advice');
const generated = standaloneCode(ajv, { inspectionValidator: 'inspection', adviceValidator: 'advice' });
// Ajv emits its small Unicode-length helper as CommonJS require even in ESM mode.
// Embed Ajv's own helper as source at build time, preserving Unicode counting.
// The resulting validators need no runtime Ajv, dynamic evaluation or fs.
const portable = generated.replace(/require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g, 'ucs2length');
if (/\brequire\s*\(/.test(portable)) throw new Error('Unexpected runtime require in standalone validators.');
const unicodeLength = typeof unicodeRuntime === 'function' ? unicodeRuntime : unicodeRuntime.default;
writeFileSync(new URL('../lib/schema-validators.mjs', import.meta.url), '// Generated by scripts/generate-validators.mjs; do not edit.\n// Unicode length helper generated from Ajv (MIT).\n' + unicodeLength.toString() + '\n' + portable + '\n');
